using Content.Client.Stylesheets;
using Content.Client.Stylesheets.Palette;
using Content.Client.UserInterface.Controls;
using Content.Shared._Aquila.Cyberware;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Aquila.Cyberware;

/// <summary>
/// Окно с результатом сканирования имплантов.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CyberwareScannerWindow : FancyWindow
{
    private static readonly LocId Empty = "cyberware-scanner-ui-empty";
    private static readonly LocId ScanQuick = "cyberware-scanner-ui-scan-quick";
    private static readonly LocId ScanDeep = "cyberware-scanner-ui-scan-deep";
    private static readonly LocId RiskValue = "cyberware-scanner-ui-risk-value";
    private static readonly LocId Adapting = "cyberware-scanner-adapting";
    private static readonly LocId NoImplants = "cyberware-scanner-ui-no-implants";
    private static readonly LocId Concealed = "cyberware-scanner-concealed";
    private static readonly LocId Stage = "cyberware-scanner-ui-stage";
    private static readonly LocId Cure = "cyberware-scanner-ui-cure";

    private const float PercentMultiplier = 100f;
    private const string ImplantBullet = "• ";

    private readonly StyleBoxFlat _lowStyle = new();
    private readonly StyleBoxFlat _elevatedStyle = new();
    private readonly StyleBoxFlat _highStyle = new();
    private readonly StyleBoxFlat _cureStyle = new(Palettes.Status.Good);

    public CyberwareScannerWindow()
    {
        RobustXamlLoader.Load(this);

        EmptyLabel.SetMessage(Loc.GetString(Empty));

        LowBar.ForegroundStyleBoxOverride = _lowStyle;
        ElevatedBar.ForegroundStyleBoxOverride = _elevatedStyle;
        HighBar.ForegroundStyleBoxOverride = _highStyle;
        CureBar.ForegroundStyleBoxOverride = _cureStyle;
    }

    /// <summary>
    /// Показывает результат сканирования.
    /// </summary>
    public void UpdateState(CyberwareScannerUiState state)
    {
        EmptyCard.Visible = false;
        ResultContainer.Visible = true;

        TargetLabel.Text = state.TargetName;
        ScanTypeLabel.Text = Loc.GetString(state.Deep ? ScanDeep : ScanQuick);

        UpdateLoad(state);
        UpdateImplants(state);
        UpdatePsychosis(state);
    }

    private void UpdateLoad(CyberwareScannerUiState state)
    {
        var critical = MathF.Max(state.CriticalLevel, 0f);
        var warning = Math.Clamp(state.WarningLevel, 0f, critical);
        var threshold = Math.Clamp(state.Threshold, warning, critical);

        SetSegment(LowBar, LowLegend, 0f, warning, state.Risk);
        SetSegment(ElevatedBar, ElevatedLegend, warning, threshold, state.Risk);
        SetSegment(HighBar, HighLegend, threshold, critical, state.Risk);

        var isCritical = state.Risk >= critical;
        _lowStyle.BackgroundColor = isCritical ? Palettes.Status.Critical : Palettes.Status.Good;
        _elevatedStyle.BackgroundColor = isCritical ? Palettes.Status.Critical : Palettes.Status.Warning;
        _highStyle.BackgroundColor = isCritical ? Palettes.Status.Critical : Palettes.Status.Bad;

        LevelLabel.Text = Loc.GetString(state.Level);
        LevelLabel.SetOnlyStyleClass(GetStatusClass(state.Risk, warning, threshold, critical));

        var percent = critical > 0f ? Math.Clamp(state.Risk / critical, 0f, 1f) * PercentMultiplier : 0f;
        RiskLabel.Text = Loc.GetString(RiskValue,
            ("risk", (int) state.Risk),
            ("max", (int) critical),
            ("percent", (int) percent));

        CountLabel.Text = state.ImplantCount.ToString();

        AdaptingLabel.Visible = state.Adapting;
        if (state.Adapting)
            AdaptingLabel.SetMessage(Loc.GetString(Adapting), Palettes.Status.Warning);
    }

    private void UpdateImplants(CyberwareScannerUiState state)
    {
        ImplantList.RemoveAllChildren();
        foreach (var implant in state.Implants)
        {
            ImplantList.AddChild(new Label { Text = ImplantBullet + implant, ClipText = true });
        }

        if (state.Implants.Count == 0)
        {
            ImplantList.AddChild(new Label
            {
                Text = Loc.GetString(NoImplants),
                ClipText = true,
                StyleClasses = { StyleClass.LabelSubText },
            });
        }

        ConcealedLabel.Visible = state.Concealed > 0;
        ConcealedLabel.Text = Loc.GetString(Concealed, ("count", state.Concealed));
    }

    private void UpdatePsychosis(CyberwareScannerUiState state)
    {
        PsychosisSection.Visible = state.PsychosisStage != null;
        if (state.PsychosisStage is { } stage)
            StageLabel.Text = Loc.GetString(Stage, ("stage", Loc.GetString(stage)));

        CureBar.Visible = state.CureProgress != null;
        if (state.CureProgress is { } cure)
        {
            CureBar.Value = cure;
            CureText.Text = Loc.GetString(Cure, ("percent", (int) (cure * PercentMultiplier)));
        }
    }

    private static void SetSegment(ProgressBar bar, Label legend, float from, float to, float risk)
    {
        var size = to - from;
        var visible = size > 0f;
        bar.Visible = visible;
        legend.Visible = visible;
        if (!visible)
            return;

        bar.SizeFlagsStretchRatio = size;
        legend.SizeFlagsStretchRatio = size;
        bar.MinValue = 0f;
        bar.MaxValue = size;
        bar.Value = Math.Clamp(risk - from, 0f, size);
    }

    private static string GetStatusClass(float risk, float warning, float threshold, float critical)
    {
        if (risk >= critical)
            return StyleClass.StatusCritical;

        if (risk >= threshold)
            return StyleClass.StatusBad;

        return risk >= warning ? StyleClass.StatusWarning : StyleClass.StatusGood;
    }
}
