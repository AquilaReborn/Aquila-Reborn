using System.Numerics;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Aquila.ProfileImage.UI;

/// <summary>
/// Window that shows the whole character profile image scaled down to the window area limits.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ProfileImageViewerWindow : FancyWindow
{
    private const float MaxScreenAreaFraction = 0.4f;
    private const float MaxScreenSideFraction = 0.9f;
    private const float WindowPaddingX = 16f;
    private const float WindowPaddingY = 48f;
    private const float MinImageScale = 0.01f;

    private static readonly Vector2 MinWindowSize = new(200f, 200f);

    public ProfileImageViewerWindow()
    {
        RobustXamlLoader.Load(this);

        MinSize = MinWindowSize;
    }

    /// <summary>
    /// Shows the given texture scaled so that the whole image fits the window area limits.
    /// </summary>
    /// <param name="texture">Texture to display.</param>
    public void SetImage(Texture texture)
    {
        ArtTexture.Texture = texture;

        var tex = (Vector2) texture.Size;
        var screen = UserInterfaceManager.RootControl.Size;
        var scale = ComputeImageScale(tex, screen);
        var image = tex * scale;

        ArtTexture.SetSize = image;
        SetSize = Vector2.Max(image + new Vector2(WindowPaddingX, WindowPaddingY), MinWindowSize);
    }

    private static float ComputeImageScale(Vector2 size, Vector2 screen)
    {
        var maxArea = screen.X * screen.Y * MaxScreenAreaFraction;
        var a = size.X * size.Y;
        var b = size.X * WindowPaddingY + size.Y * WindowPaddingX;
        var c = WindowPaddingX * WindowPaddingY - maxArea;

        var scale = 1f;
        if (a + b + c > 0f)
        {
            var discriminant = b * b - 4f * a * c;
            scale = discriminant <= 0f
                ? MinImageScale
                : (-b + MathF.Sqrt(discriminant)) / (2f * a);
        }

        scale = MathF.Min(scale, (screen.X * MaxScreenSideFraction - WindowPaddingX) / size.X);
        scale = MathF.Min(scale, (screen.Y * MaxScreenSideFraction - WindowPaddingY) / size.Y);

        return Math.Clamp(scale, MinImageScale, 1f);
    }
}
