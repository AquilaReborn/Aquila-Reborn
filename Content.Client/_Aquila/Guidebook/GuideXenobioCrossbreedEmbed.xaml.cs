namespace Content.Client._Aquila.Guidebook;

/// <summary>
/// Карточка категории гибридных экстрактов слаймов в руководстве с описанием каждого экстракта.
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideXenobioCrossbreedEmbed : BoxContainer, IDocumentTag, ISearchableControl
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly ILogManager _logManager = default!;

    private readonly ISawmill _sawmill;

    public GuideXenobioCrossbreedEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;

        _sawmill = _logManager.GetSawmill("guide_xenobio_crossbreed");
    }

    /// <summary>
    /// Проверяет, содержит ли карточка искомый текст.
    /// </summary>
    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    /// <summary>
    /// Скрывает или показывает карточку в зависимости от поискового запроса и раскрывает найденные карточки.
    /// </summary>
    public void SetHiddenState(bool state, string query)
    {
        var matches = CheckMatchesSearch(query);
        Visible = matches ? state : !state;
        CategoryCollapsible.BodyVisible = matches && state && query.Length > 0;
    }

    /// <summary>
    /// Создаёт карточку по тегу руководства с аргументом Category.
    /// </summary>
    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Category", out var id))
        {
            _sawmill.Error("Xenobio crossbreed embed tag is missing category prototype argument");
            return false;
        }

        if (!_prototype.TryIndex<SlimeCrossbreedCategoryPrototype>(id, out var category))
        {
            _sawmill.Error($"Specified slime crossbreed category prototype \"{id}\" is not a valid prototype");
            return false;
        }

        GenerateControl(category);

        control = this;
        return true;
    }

    private void GenerateControl(SlimeCrossbreedCategoryPrototype category)
    {
        CategoryHeading.Title = Loc.GetString("guidebook-xenobio-crossbreed-category-display",
            ("category", Loc.GetString(category.Name)));

        CategoryDescription.SetMarkup(Loc.GetString("guidebook-xenobio-crossbreed-category-description",
            ("required", category.Required),
            ("color", category.Color)));

        foreach (var result in category.Results.Values)
        {
            ExtractsContainer.AddChild(CreateExtractRow(result));
        }
    }

    private Control CreateExtractRow(EntProtoId result)
    {
        var extract = _prototype.Index(result);

        var nameMsg = new FormattedMessage();
        nameMsg.AddMarkupOrThrow(Loc.GetString("guidebook-xenobio-crossbreed-extract-name-display",
            ("extract", extract.Name)));

        var nameLabel = new GuidebookRichPrototypeLink { LinkedPrototype = extract };
        nameLabel.SetMessage(nameMsg);

        var descriptionLabel = new RichTextLabel { HorizontalExpand = true };
        descriptionLabel.SetMarkup(extract.Description);

        var text = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(8, 0, 0, 0),
        };
        text.AddChild(nameLabel);
        text.AddChild(descriptionLabel);

        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(8, 4, 8, 4),
        };
        content.AddChild(new GuideEntityEmbed(result, false, false));
        content.AddChild(text);

        var row = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 4, 0, 0),
            StyleClasses = { StyleNano.StyleClassBackgroundBaseLight },
        };
        row.AddChild(content);

        return row;
    }
}
