/// <summary>
/// Карточка экстракта слайма в руководстве с его реакциями на реагенты.
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideXenobioExtractEmbed : BoxContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly ILogManager _logManager = default!;

    private readonly ISawmill _sawmill;

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuideXenobioExtractEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;

        _sawmill = _logManager.GetSawmill("guide_xenobio_extract");
    }

    public GuideXenobioExtractEmbed(XenobioExtractGuidePrototype guide) : this()
    {
        GenerateControl(guide);
    }

    /// <summary>
    /// Проверяет, содержит ли карточка искомый текст.
    /// </summary>
    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    /// <summary>
    /// Скрывает или показывает карточку в зависимости от поискового запроса и раскрывает найденные карточки.
    /// </summary>
    public void SetHiddenState(bool state, string query)
    {
        var matches = CheckMatchesSearch(query);
        Visible = matches ? state : !state;
        ExtractCollapsible.BodyVisible = matches && state && query.Length > 0;
    }

    /// <summary>
    /// Создаёт карточку по тегу руководства с аргументом Guide.
    /// </summary>
    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Guide", out var id))
        {
            _sawmill.Error("Xenobio extract embed tag is missing guide prototype argument");
            return false;
        }

        if (!_prototype.TryIndex<XenobioExtractGuidePrototype>(id, out var guide))
        {
            _sawmill.Error($"Specified xenobio extract guide prototype \"{id}\" is not a valid prototype");
            return false;
        }

        GenerateControl(guide);

        control = this;
        return true;
    }

    private void GenerateControl(XenobioExtractGuidePrototype guide)
    {
        var extract = _prototype.Index(guide.Extract);
        RepresentedPrototype = extract;

        ExtractHeading.Title = Loc.GetString("guidebook-xenobio-extract-name-display", ("extract", extract.Name));

        if (ExtractHeading.Label.Parent is { } headingBox)
        {
            var icon = new GuideEntityEmbed(guide.Extract, false, false);
            headingBox.AddChild(icon);
            icon.SetPositionInParent(ExtractHeading.Label.GetPositionInParent());
        }

        foreach (var reaction in guide.Reactions)
        {
            ReactionsContainer.AddChild(CreateReactionRow(reaction));
        }
    }

    private Control CreateReactionRow(XenobioExtractGuideReaction reaction)
    {
        var reagent = _prototype.Index(reaction.Reagent);

        var nameMsg = new FormattedMessage();
        nameMsg.AddMarkupOrThrow(Loc.GetString("guidebook-xenobio-extract-reagent-name-display",
            ("reagent", reagent.LocalizedName),
            ("color", reagent.SubstanceColor)));

        var nameLabel = new GuidebookRichPrototypeLink { LinkedPrototype = reagent };
        nameLabel.SetMessage(nameMsg);

        var descriptionLabel = new RichTextLabel { HorizontalExpand = true };
        descriptionLabel.SetMarkup(Loc.GetString(reaction.Description));

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(8, 4, 8, 4),
        };
        content.AddChild(nameLabel);
        content.AddChild(descriptionLabel);

        var row = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 4, 0, 0),
            StyleClasses = { StyleNano.StyleClassBackgroundBaseLight },
        };
        row.AddChild(content);

        return row;
    }
}
