using System.Numerics;
using Content.Client._Aquila.Actions;
using Content.Client.Stylesheets;
using Content.Shared._Aquila.CCVars;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Aquila.Options;

[GenerateTypedNameReferences]
public sealed partial class AquilaTab : Control
{
    private static readonly Vector2 ActionBindButtonSize = new(200, 0);

    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private readonly List<Action> _deferredActions = new();

    private ActionCustomizationUIController ActionCustomization =>
        UserInterfaceManager.GetUIController<ActionCustomizationUIController>();

    public AquilaTab()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        Control.AddOptionPercentSlider(AquilaCVars.RadioMusicVolume, SliderVolumeRadioMusic);
        Control.AddOptionPercentSlider(AquilaCVars.AdminMusicVolume, SliderVolumeAdminMusic);
        Control.AddOptionCheckBox(AquilaCVars.AudioEnvironment, AudioEnvironmentCheckBox);
        Control.AddOptionCheckBox(AquilaCVars.LightGlow, LightGlowCheckBox);
        Control.AddOptionPercentSlider(AquilaCVars.LightGlowIntensity, SliderLightGlowIntensity);

        Control.Initialize();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        ActionCustomization.BindsChanged += FillActionBinds;
        FillActionBinds();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        ActionCustomization.BindsChanged -= FillActionBinds;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_deferredActions.Count == 0)
            return;

        foreach (var action in _deferredActions)
        {
            action();
        }

        _deferredActions.Clear();
    }

    private void FillActionBinds()
    {
        ActionBindsContainer.RemoveAllChildren();

        var customization = ActionCustomization;
        var binds = customization.GetActionBinds();

        if (binds.Count == 0)
        {
            ActionBindsContainer.AddChild(new Label
            {
                Text = Loc.GetString("ui-options-aquila-action-binds-empty"),
                StyleClasses = { StyleClass.LabelSubText },
                Margin = new Thickness(5, 0, 0, 0),
            });
            return;
        }

        foreach (var (action, bind) in binds)
        {
            var name = _prototypeManager.TryIndex(action, out var proto) ? proto.Name : action.Id;

            var resetButton = new Button
            {
                Text = Loc.GetString("ui-options-aquila-action-binds-reset"),
                StyleClasses = { StyleClass.Negative },
            };
            resetButton.OnPressed += _ => _deferredActions.Add(() => customization.ClearBind(action));

            ActionBindsContainer.AddChild(new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Children =
                {
                    new Label
                    {
                        Text = name,
                        HorizontalExpand = true,
                        ClipText = true,
                        Margin = new Thickness(5, 0, 0, 0),
                    },
                    new Button
                    {
                        Text = bind,
                        Disabled = true,
                        MinSize = ActionBindButtonSize,
                        Margin = new Thickness(0, 0, 10, 0),
                    },
                    resetButton,
                },
            });
        }

        var resetAllButton = new Button
        {
            Text = Loc.GetString("ui-options-aquila-action-binds-reset-all"),
            StyleClasses = { StyleClass.Negative },
            HorizontalAlignment = HAlignment.Right,
            Margin = new Thickness(0, 4, 0, 0),
        };
        resetAllButton.OnPressed += _ => _deferredActions.Add(customization.ClearAllBinds);
        ActionBindsContainer.AddChild(resetAllButton);
    }
}
