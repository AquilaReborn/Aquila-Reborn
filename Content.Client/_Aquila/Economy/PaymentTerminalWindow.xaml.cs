using Content.Client.UserInterface.Controls;
using Content.Shared._Aquila.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Aquila.Economy;

[GenerateTypedNameReferences]
public sealed partial class PaymentTerminalWindow : FancyWindow
{
    private static readonly LocId NoAccountText = "payment-terminal-window-no-account";
    private static readonly LocId LinkedText = "payment-terminal-window-linked";
    private static readonly LocId BudgetText = "payment-terminal-window-budget";
    private static readonly LocId NoInvoiceText = "payment-terminal-window-no-invoice";
    private static readonly LocId AwaitingText = "payment-terminal-window-awaiting";
    private static readonly LocId FineOnlyText = "payment-terminal-window-fine-only";
    private static readonly LocId InvalidAmountText = "payment-terminal-window-invalid-amount";
    private static readonly LocId NoPurposeText = "payment-terminal-window-no-purpose";

    public event Action<int, string>? OnSetInvoice;
    public event Action? OnClearInvoice;
    public event Action? OnPrintReceipt;
    public event Action? OnLinkCard;

    public PaymentTerminalWindow()
    {
        RobustXamlLoader.Load(this);

        PurposeInput.IsValid = text => text.Length <= PaymentTerminalLimits.MaxPurposeLength;
        PurposeInput.OnTextEntered += _ => SetInvoice();
        AmountInput.OnTextEntered += _ => SetInvoice();
        SetInvoiceButton.OnPressed += _ => SetInvoice();
        ClearInvoiceButton.OnPressed += _ => OnClearInvoice?.Invoke();
        PrintReceiptButton.OnPressed += _ => OnPrintReceipt?.Invoke();
        LinkCardButton.OnPressed += _ => OnLinkCard?.Invoke();
    }

    /// <summary>
    /// Обновляет привязанный счёт или бюджет отдела, текущий выставленный счёт, вид терминала штрафов, доступность формы владельца
    /// и кнопки привязки карты.
    /// </summary>
    public void UpdateState(PaymentTerminalUiState state)
    {
        if (state.BudgetName is { } budget)
            AccountLabel.Text = Loc.GetString(BudgetText, ("budget", budget));
        else
            AccountLabel.Text = state.LinkedOwnerName != null
                ? Loc.GetString(LinkedText, ("owner", state.LinkedOwnerName))
                : Loc.GetString(NoAccountText);

        FineOnlyLabel.Visible = state.FineOnly;
        FineOnlyLabel.Text = Loc.GetString(FineOnlyText);

        InvoiceLabel.Text = state.Ready
            ? Loc.GetString(AwaitingText, ("amount", state.Amount), ("purpose", state.Purpose))
            : Loc.GetString(NoInvoiceText);

        OwnerForm.Visible = state.IsOwner || state.CanLinkCard;
        LinkCardButton.Visible = state.CanLinkCard;
        ErrorLabel.Visible = false;
    }

    private void SetInvoice()
    {
        if (!int.TryParse(AmountInput.Text, out var amount) || amount <= 0)
        {
            ShowError(InvalidAmountText);
            return;
        }

        var purpose = PurposeInput.Text.Trim();
        if (purpose.Length == 0)
        {
            ShowError(NoPurposeText);
            return;
        }

        ErrorLabel.Visible = false;
        OnSetInvoice?.Invoke(amount, purpose);
    }

    private void ShowError(LocId message)
    {
        ErrorLabel.Text = Loc.GetString(message);
        ErrorLabel.Visible = true;
    }
}
