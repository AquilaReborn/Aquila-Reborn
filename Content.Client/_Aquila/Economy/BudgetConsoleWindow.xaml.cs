using Content.Client.UserInterface.Controls;
using Content.Shared._Aquila.Economy;
using Content.Shared.Cargo.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Aquila.Economy;

[GenerateTypedNameReferences]
public sealed partial class BudgetConsoleWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private static readonly LocId EmptyText = "budget-console-empty";
    private static readonly LocId UnknownAccountText = "budget-console-unknown-account";
    private static readonly LocId SourceText = "budget-console-source";
    private static readonly LocId CommentText = "budget-console-comment";

    public BudgetConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    /// <summary>
    /// Обновляет список записей журнала бюджета.
    /// </summary>
    public void UpdateState(BudgetConsoleUiState state)
    {
        EntriesContainer.RemoveAllChildren();

        if (state.Entries.Count == 0)
        {
            EntriesContainer.AddChild(new Label
            {
                Text = Loc.GetString(EmptyText),
                StyleClasses = { "LabelSubText" },
                Margin = new Thickness(4, 6),
            });
            return;
        }

        foreach (var entry in state.Entries)
        {
            EntriesContainer.AddChild(CreateEntryRow(entry));
        }
    }

    private BoxContainer CreateEntryRow(BudgetConsoleEntry entry)
    {
        var account = _prototypeManager.TryIndex<CargoAccountPrototype>(entry.Account, out var accountPrototype)
            ? Loc.GetString(accountPrototype.Code)
            : Loc.GetString(UnknownAccountText);

        var reason = Loc.GetString(entry.Reason, ("party", entry.Source ?? string.Empty));
        var delta = entry.Delta > 0 ? $"+{entry.Delta}" : entry.Delta.ToString();

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        header.AddChild(new Label
        {
            Text = entry.Time.ToString(@"hh\:mm\:ss"),
            MinWidth = 64,
            StyleClasses = { "LabelSubText" },
        });

        header.AddChild(new Label
        {
            Text = account,
            ToolTip = account,
            MinWidth = 52,
            ClipText = true,
        });

        header.AddChild(new Label
        {
            Text = delta,
            ToolTip = delta,
            MinWidth = 84,
            HorizontalAlignment = HAlignment.Right,
            StyleClasses = { entry.Delta > 0 ? "Good" : "Danger" },
        });

        header.AddChild(new Label
        {
            Text = reason,
            ToolTip = reason,
            HorizontalExpand = true,
            ClipText = true,
        });

        header.AddChild(new Label
        {
            Text = entry.BalanceAfter.ToString(),
            MinWidth = 88,
            HorizontalAlignment = HAlignment.Right,
        });

        row.AddChild(header);

        if (entry.Source == null && entry.Comment == null)
            return row;

        var details = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        if (entry.Source != null)
        {
            var source = Loc.GetString(SourceText, ("source", entry.Source));
            details.AddChild(new Label
            {
                Text = source,
                ToolTip = source,
                StyleClasses = { "LabelSubText" },
                HorizontalExpand = true,
                ClipText = true,
            });
        }

        if (entry.Comment != null)
        {
            var comment = Loc.GetString(CommentText, ("comment", entry.Comment));
            details.AddChild(new Label
            {
                Text = comment,
                ToolTip = comment,
                StyleClasses = { "LabelSubText" },
                HorizontalExpand = true,
                ClipText = true,
            });
        }

        row.AddChild(details);
        return row;
    }
}
