using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Aquila.Administration;
using Content.Shared.Humanoid.Prototypes;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Aquila.Administration;

[GenerateTypedNameReferences]
public sealed partial class AdminCharacterSpawnWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entities = default!;
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    private static readonly LocId CloneLabel = "aquila-admin-character-clone";
    private static readonly LocId ErrorLabel = "aquila-admin-character-error";
    private static readonly LocId LobbyLabel = "aquila-admin-character-lobby";
    private static readonly LocId NoOutfitLabel = "aquila-admin-character-no-outfit";
    private static readonly LocId PresetsLabel = "aquila-admin-character-presets";
    private static readonly LocId SpawnLabel = "aquila-admin-character-spawn";
    private static readonly LocId TargetLabel = "aquila-admin-character-target";
    private static readonly LocId TargetLobbyLabel = "aquila-admin-character-target-lobby";

    private enum Source
    {
        Target,
        Lobby,
        TargetLobby,
        Preset,
    }

    private AdminCharacterSpawnState? _state;
    private KeyValuePair<int, HumanoidCharacterProfile>[] _profiles = [];
    private KeyValuePair<int, HumanoidCharacterProfile>[] _targetProfiles = [];
    private readonly ProtoId<HumanoidProfilePrototype>[] _presets;
    private readonly ProtoId<StartingGearPrototype>[] _gear;
    private int _profileIndex;
    private EntityUid? _dummy;
    private ProtoId<StartingGearPrototype>? _selectedGear;

    internal event Action<AdminCharacterSpawnRequest>? OnConfirm;

    /// <summary>Создаёт окно настройки персонажа.</summary>
    public AdminCharacterSpawnWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _presets = _prototypes.EnumeratePrototypes<HumanoidProfilePrototype>().OrderBy(p => p.ID).Select(p => new ProtoId<HumanoidProfilePrototype>(p.ID)).ToArray();
        _gear = _prototypes.EnumeratePrototypes<StartingGearPrototype>().Where(p => !p.Abstract).OrderBy(p => p.ID).Select(p => new ProtoId<StartingGearPrototype>(p.ID)).ToArray();

        ProfileSource.AddItem(Loc.GetString(TargetLabel), (int) Source.Target);
        ProfileSource.AddItem(Loc.GetString(LobbyLabel), (int) Source.Lobby);
        ProfileSource.AddItem(Loc.GetString(TargetLobbyLabel), (int) Source.TargetLobby);
        if (_presets.Length > 0)
            ProfileSource.AddItem(Loc.GetString(PresetsLabel), (int) Source.Preset);

        for (var index = 0; index < _presets.Length; index++)
            Preset.AddItem(_presets[index].Id, index);

        ProfileSource.OnItemSelected += args =>
        {
            ProfileSource.SelectId(args.Id);
            _profileIndex = 0;
            UpdatePreview();
        };
        Preset.OnItemSelected += args =>
        {
            Preset.SelectId(args.Id);
            UpdatePreview();
        };
        PreviousProfile.OnPressed += _ => CycleProfile(-1);
        NextProfile.OnPressed += _ => CycleProfile(1);
        SearchGear.OnTextChanged += _ => PopulateGear();
        NameOverride.OnTextChanged += _ => UpdateName();
        Confirm.OnPressed += _ => Submit();
        PopulateGear();
    }

    internal void UpdateState(AdminCharacterSpawnState state)
    {
        _state = state;
        InsideStorage.Visible = state.CanSpawnInsideStorage;
        _profiles = state.Profiles.OrderBy(entry => entry.Key).ToArray();
        _targetProfiles = state.TargetProfiles.OrderBy(entry => entry.Key).ToArray();
        ProfileSource.SetItemDisabled(ProfileSource.GetIdx((int) Source.TargetLobby), _targetProfiles.Length == 0);
        _profileIndex = 0;
        if ((ProfileSource.SelectedId == (int) Source.Lobby || ProfileSource.SelectedId == (int) Source.TargetLobby) && ActiveProfiles.Length == 0)
            ProfileSource.SelectId((int) Source.Target);
        ProfileSource.SetItemDisabled(ProfileSource.GetIdx((int) Source.Lobby), _profiles.Length == 0);
        Confirm.Text = Loc.GetString(state.Clone ? CloneLabel : SpawnLabel);
        Confirm.Disabled = false;
        UpdatePreview();
    }

    private KeyValuePair<int, HumanoidCharacterProfile>[] ActiveProfiles => (Source) ProfileSource.SelectedId switch
    {
        Source.Lobby => _profiles,
        Source.TargetLobby => _targetProfiles,
        _ => [],
    };

    private void CycleProfile(int step)
    {
        var count = ActiveProfiles.Length;
        if (count == 0)
            return;

        _profileIndex = (_profileIndex + step + count) % count;
        UpdatePreview();
    }

    private HumanoidCharacterProfile? GetProfile()
    {
        return (Source) ProfileSource.SelectedId switch
        {
            Source.Lobby or Source.TargetLobby when ActiveProfiles.Length > 0 => ActiveProfiles[_profileIndex].Value,
            Source.Preset when _presets.Length > 0 => _prototypes.TryIndex(_presets[Preset.SelectedId], out var preset) ? preset.Profile : null,
            _ => _state?.TargetProfile,
        };
    }

    private void PopulateGear()
    {
        Gear.Clear();
        AddGear(Loc.GetString(NoOutfitLabel), null);
        var filter = SearchGear.Text.Trim();
        foreach (var gear in _gear)
        {
            if (gear.Id.Contains(filter, StringComparison.OrdinalIgnoreCase))
                AddGear(gear.Id, gear);
        }
    }

    private void AddGear(string text, ProtoId<StartingGearPrototype>? gear)
    {
        var item = new ItemList.Item(Gear) { Text = text };
        Gear.Add(item);
        item.Selected = gear == _selectedGear;
        item.OnSelected += _ =>
        {
            _selectedGear = gear;
            SelectedGear.Text = text;
            UpdatePreview();
        };

        if (item.Selected)
            SelectedGear.Text = text;
    }

    private void UpdatePreview()
    {
        var source = (Source) ProfileSource.SelectedId;
        Preset.Visible = source == Source.Preset;
        PreviousProfile.Disabled = NextProfile.Disabled = ActiveProfiles.Length < 2;
        ClearPreview();
        if (GetProfile() is not { } profile)
            return;

        ProtoId<HumanoidProfilePrototype>? preset = source == Source.Preset ? (ProtoId<HumanoidProfilePrototype>?) _presets[Preset.SelectedId] : null;
        var dummy = UserInterfaceManager.GetUIController<AdminCharacterSpawnUIController>()
            .CreatePreview(profile, preset, _selectedGear);
        _dummy = dummy;
        Preview.SetEntity(dummy);
        NameOverride.PlaceHolder = profile.Name;
        UpdateName();
    }

    private void UpdateName()
    {
        ProfileName.Text = string.IsNullOrWhiteSpace(NameOverride.Text) ? GetProfile()?.Name : NameOverride.Text.Trim();
    }

    private void Submit()
    {
        if (_state == null || Confirm.Disabled)
            return;

        var source = (Source) ProfileSource.SelectedId;
        int? slot = ActiveProfiles.Length > 0 ? ActiveProfiles[_profileIndex].Key : null;
        ProtoId<HumanoidProfilePrototype>? preset = source == Source.Preset ? (ProtoId<HumanoidProfilePrototype>?) _presets[Preset.SelectedId] : null;
        Confirm.Disabled = true;
        Status.Visible = false;
        OnConfirm?.Invoke(new AdminCharacterSpawnRequest
        {
            Slot = slot,
            UseTargetSlot = source == Source.TargetLobby,
            SpawnInsideStorage = InsideStorage.Visible && InsideStorage.Pressed,
            Preset = preset,
            Gear = _selectedGear,
            Name = NameOverride.Text.Trim(),
        });
    }

    internal void ShowError()
    {
        Status.Text = Loc.GetString(ErrorLabel);
        Status.Visible = true;
        Confirm.Disabled = false;
    }

    internal void ClearPreview()
    {
        Preview.SetEntity((EntityUid?) null);
        if (_dummy is { } dummy)
            _entities.DeleteEntity(dummy);
        _dummy = null;
    }

}
