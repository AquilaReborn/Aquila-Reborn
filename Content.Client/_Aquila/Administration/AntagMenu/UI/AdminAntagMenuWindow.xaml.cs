using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Aquila.Administration.AntagMenu.DataDefinitions;
using Content.Shared._Aquila.Administration.AntagMenu.Eui;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Aquila.Administration.AntagMenu.UI;

/// <summary>
/// Окно администратора со списком антагонистов, их ролей и целей.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AdminAntagMenuWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    private static readonly LocId CountText = "admin-antag-menu-count";
    private static readonly LocId UsernameText = "admin-antag-menu-username";
    private static readonly LocId RolesText = "admin-antag-menu-roles";
    private static readonly LocId NoRolesText = "admin-antag-menu-no-roles";
    private static readonly LocId EntryText = "admin-antag-menu-entry";
    private static readonly LocId EntryRolesText = "admin-antag-menu-entry-roles";
    private static readonly LocId UnknownNameText = "admin-antag-menu-unknown-name";
    private static readonly LocId ObjectiveCountText = "admin-antag-menu-objective-count";
    private static readonly LocId ObjectiveProgressText = "admin-antag-menu-objective-progress";
    private static readonly LocId ObjectiveSetText = "admin-antag-menu-objective-set";
    private static readonly LocId ObjectiveMinusText = "admin-antag-menu-objective-minus";
    private static readonly LocId ObjectivePlusText = "admin-antag-menu-objective-plus";
    private static readonly LocId ObjectiveRemoveText = "admin-antag-menu-objective-remove";

    private readonly List<string> _grantRoleIds = new();
    private readonly List<string> _objectivePrototypeIds = new();
    private readonly List<string> _removeRoleIds = new();
    private readonly Dictionary<Button, NetEntity> _mindButtons = new();
    private AdminAntagMenuEuiState? _state;
    private NetEntity? _selectedMind;
    private string? _grantRoleId;
    private string? _removeRoleId;
    private string? _objectivePrototypeId;
    private bool _showAll;

    /// <summary>
    /// Запрос на повторную сборку состояния.
    /// </summary>
    public event Action? OnRefresh;

    /// <summary>
    /// Просьба прислать цели, которые подходят выбранному разуму.
    /// </summary>
    public event Action<NetEntity>? OnRequestObjectives;

    /// <summary>
    /// Просьба выдать выбранному разуму цель из прототипа.
    /// </summary>
    public event Action<NetEntity, string>? OnAddObjective;

    /// <summary>
    /// Просьба удалить цель разума.
    /// </summary>
    public event Action<NetEntity, NetEntity>? OnRemoveObjective;

    /// <summary>
    /// Просьба задать требуемое значение числовой цели.
    /// </summary>
    public event Action<NetEntity, NetEntity, int>? OnSetObjectiveTarget;

    /// <summary>
    /// Просьба удалить все цели разума.
    /// </summary>
    public event Action<NetEntity>? OnRemoveAllObjectives;

    /// <summary>
    /// Просьба выдать разуму антагонистскую роль.
    /// </summary>
    public event Action<NetEntity, string>? OnGrantRole;

    /// <summary>
    /// Просьба снять с разума антагонистскую роль.
    /// </summary>
    public event Action<NetEntity, string>? OnRemoveRole;

    /// <summary>
    /// Создаёт окно и подключает обработчики элементов.
    /// </summary>
    public AdminAntagMenuWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        ShowAllCheckBox.OnToggled += args =>
        {
            _showAll = args.Pressed;
            PopulateMinds();
        };
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        GrantRoleButton.OnPressed += _ => GrantSelectedRole();
        RemoveRoleButton.OnPressed += _ => RemoveSelectedRole();
        RemoveAllObjectivesButton.OnPressed += _ => RemoveAllSelectedObjectives();
        AddObjectiveButton.OnPressed += _ => AddSelectedObjective();
        AddObjectiveOption.Filterable = true;
        AddObjectiveOption.OnItemSelected += args =>
        {
            AddObjectiveOption.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _objectivePrototypeIds.Count)
                _objectivePrototypeId = _objectivePrototypeIds[args.Id];
        };
        GrantRoleOption.OnItemSelected += args =>
        {
            GrantRoleOption.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _grantRoleIds.Count)
                _grantRoleId = _grantRoleIds[args.Id];
        };
        RemoveRoleOption.OnItemSelected += args =>
        {
            RemoveRoleOption.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _removeRoleIds.Count)
                _removeRoleId = _removeRoleIds[args.Id];
        };
    }

    /// <summary>
    /// Обновляет список разумов, ролей и целей по новому состоянию.
    /// </summary>
    public void UpdateState(AdminAntagMenuEuiState state)
    {
        _state = state;
        StatusLabel.Visible = false;

        if (_selectedMind != null && state.Minds.All(mind => mind.Mind != _selectedMind))
            _selectedMind = null;

        PopulateMinds();
        PopulateDetails();

        if (_selectedMind is { } mind)
            OnRequestObjectives?.Invoke(mind);
    }

    /// <summary>
    /// Показывает текст ошибки, полученный с сервера.
    /// </summary>
    public void ShowError(LocId messageKey)
    {
        StatusLabel.Text = Loc.GetString(messageKey);
        StatusLabel.Visible = true;
    }

    /// <summary>
    /// Заполняет список доступными целями, которые прислал сервер.
    /// </summary>
    public void UpdateObjectiveOptions(NetEntity mind, List<string> prototypes)
    {
        if (_selectedMind != mind)
            return;

        _objectivePrototypeIds.Clear();
        _objectivePrototypeIds.AddRange(prototypes);

        AddObjectiveOption.Clear();
        for (var i = 0; i < prototypes.Count; i++)
            AddObjectiveOption.AddItem(GetObjectiveName(prototypes[i]), i);

        var selected = _objectivePrototypeId == null
            ? -1
            : _objectivePrototypeIds.IndexOf(_objectivePrototypeId);

        if (selected >= 0)
            AddObjectiveOption.Select(selected);
        else
            _objectivePrototypeId = prototypes.Count > 0 ? prototypes[0] : null;

        var hasOptions = prototypes.Count > 0;
        AddObjectiveOption.Disabled = !hasOptions;
        AddObjectiveButton.Disabled = !hasOptions;
    }

    private void PopulateMinds()
    {
        AntagsList.RemoveAllChildren();
        _mindButtons.Clear();
        if (_state == null)
            return;

        var antags = _state.Minds.Count(mind => mind.Roles.Count > 0);
        CountLabel.Text = Loc.GetString(CountText, ("antags", antags), ("total", _state.Minds.Count));

        var shown = _state.Minds.Where(mind => _showAll || mind.Roles.Count > 0).ToList();
        NoAntagsLabel.Visible = shown.Count == 0;

        foreach (var mind in shown)
        {
            var text = GetMindLabel(mind);
            var button = new Button
            {
                Text = text,
                ToolTip = text,
                ToggleMode = true,
                Pressed = mind.Mind == _selectedMind,
                ClipText = true,
                HorizontalExpand = true,
            };
            var netMind = mind.Mind;
            button.OnPressed += _ => SelectMind(netMind);
            _mindButtons.Add(button, netMind);
            AntagsList.AddChild(button);
        }
    }

    private void SelectMind(NetEntity mind)
    {
        var changed = _selectedMind != mind;
        _selectedMind = mind;
        foreach (var (button, netMind) in _mindButtons)
            button.Pressed = netMind == mind;

        if (changed)
        {
            _objectivePrototypeId = null;
            _objectivePrototypeIds.Clear();
            AddObjectiveOption.Clear();
            AddObjectiveOption.Disabled = true;
            AddObjectiveButton.Disabled = true;
            OnRequestObjectives?.Invoke(mind);
        }

        PopulateDetails();
    }

    private void PopulateDetails()
    {
        var mind = _selectedMind is { } selected
            ? _state?.Minds.Find(entry => entry.Mind == selected)
            : null;

        if (mind == null)
        {
            NoSelectionLabel.Visible = true;
            DetailsContainer.Visible = false;
            return;
        }

        NoSelectionLabel.Visible = false;
        DetailsContainer.Visible = true;

        NameLabel.Text = GetMindName(mind);
        UsernameLabel.Text = mind.Username.Length > 0
            ? Loc.GetString(UsernameText, ("username", mind.Username))
            : string.Empty;
        UsernameLabel.Visible = mind.Username.Length > 0;

        var roles = mind.Roles.Select(GetAntagName).ToList();
        RolesLabel.Text = roles.Count > 0
            ? Loc.GetString(RolesText, ("roles", string.Join(", ", roles)))
            : Loc.GetString(NoRolesText);

        PopulateGrantRole(mind);
        PopulateRemoveRole(mind);
        PopulateObjectives(mind);
    }

    private void PopulateGrantRole(AdminAntagMenuMindData mind)
    {
        GrantRoleOption.Clear();
        _grantRoleIds.Clear();

        if (_state != null)
        {
            foreach (var antag in _state.GrantableAntags)
            {
                if (mind.Roles.Contains(antag))
                    continue;

                _grantRoleIds.Add(antag);
                GrantRoleOption.AddItem(GetAntagName(antag), _grantRoleIds.Count - 1);
            }
        }

        var selected = _grantRoleId == null ? -1 : _grantRoleIds.IndexOf(_grantRoleId);
        if (selected >= 0)
            GrantRoleOption.Select(selected);
        else
            _grantRoleId = _grantRoleIds.Count > 0 ? _grantRoleIds[0] : null;

        var hasOptions = _grantRoleIds.Count > 0;
        GrantRoleOption.Disabled = !hasOptions;
        GrantRoleButton.Disabled = !hasOptions;
    }

    private void PopulateRemoveRole(AdminAntagMenuMindData mind)
    {
        RemoveRoleOption.Clear();
        _removeRoleIds.Clear();

        foreach (var antag in mind.Roles)
        {
            _removeRoleIds.Add(antag);
            RemoveRoleOption.AddItem(GetAntagName(antag), _removeRoleIds.Count - 1);
        }

        var selected = _removeRoleId == null ? -1 : _removeRoleIds.IndexOf(_removeRoleId);
        if (selected >= 0)
            RemoveRoleOption.Select(selected);
        else
            _removeRoleId = _removeRoleIds.Count > 0 ? _removeRoleIds[0] : null;

        var hasOptions = _removeRoleIds.Count > 0;
        RemoveRoleOption.Disabled = !hasOptions;
        RemoveRoleButton.Disabled = !hasOptions;
    }

    private void PopulateObjectives(AdminAntagMenuMindData mind)
    {
        ObjectivesList.RemoveAllChildren();
        NoObjectivesLabel.Visible = mind.Objectives.Count == 0;
        RemoveAllObjectivesButton.Disabled = mind.Objectives.Count == 0;

        foreach (var objective in mind.Objectives)
            ObjectivesList.AddChild(CreateObjectiveRow(mind, objective));
    }

    private Control CreateObjectiveRow(AdminAntagMenuMindData mind, AdminAntagMenuObjectiveData objective)
    {
        var name = objective.Title.Length > 0 ? objective.Title : GetObjectiveName(objective.Prototype);
        var percent = (int) MathF.Round(Math.Clamp(objective.Progress, 0f, 1f) * 100f);

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        row.AddChild(new Label
        {
            Text = name,
            ClipText = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            ToolTip = objective.Description.Length > 0 ? objective.Description : name,
        });

        if (objective.Target is { } target)
        {
            var current = objective.Current ?? 0;
            row.AddChild(new Label
            {
                Text = Loc.GetString(ObjectiveCountText, ("current", current), ("target", target)),
                MinWidth = 64,
                VerticalAlignment = VAlignment.Center,
            });

            var input = new LineEdit
            {
                Text = target.ToString(),
                MinWidth = 56,
                ToolTip = Loc.GetString(ObjectiveProgressText, ("percent", percent)),
            };
            row.AddChild(input);

            var set = new Button { Text = Loc.GetString(ObjectiveSetText) };
            set.OnPressed += _ =>
            {
                if (int.TryParse(input.Text, out var value))
                    OnSetObjectiveTarget?.Invoke(mind.Mind, objective.Objective, value);
            };
            row.AddChild(set);

            var minus = new Button
            {
                Text = Loc.GetString(ObjectiveMinusText),
                ToolTip = Loc.GetString(ObjectiveProgressText, ("percent", percent)),
            };
            minus.OnPressed += _ =>
                OnSetObjectiveTarget?.Invoke(mind.Mind, objective.Objective, Math.Max(1, target - 1));
            row.AddChild(minus);

            var plus = new Button { Text = Loc.GetString(ObjectivePlusText) };
            plus.OnPressed += _ => OnSetObjectiveTarget?.Invoke(mind.Mind, objective.Objective, target + 1);
            row.AddChild(plus);
        }
        else
        {
            row.AddChild(new Label
            {
                Text = Loc.GetString(ObjectiveProgressText, ("percent", percent)),
                MinWidth = 64,
                VerticalAlignment = VAlignment.Center,
            });
        }

        var remove = new Button { Text = Loc.GetString(ObjectiveRemoveText) };
        remove.OnPressed += _ => OnRemoveObjective?.Invoke(mind.Mind, objective.Objective);
        row.AddChild(remove);

        return row;
    }

    private void AddSelectedObjective()
    {
        if (_selectedMind is not { } mind || _objectivePrototypeId == null)
            return;

        OnAddObjective?.Invoke(mind, _objectivePrototypeId);
    }

    private void RemoveAllSelectedObjectives()
    {
        if (_selectedMind is { } mind)
            OnRemoveAllObjectives?.Invoke(mind);
    }

    private void GrantSelectedRole()
    {
        if (_selectedMind is not { } mind || _grantRoleId == null)
            return;

        OnGrantRole?.Invoke(mind, _grantRoleId);
    }

    private void RemoveSelectedRole()
    {
        if (_selectedMind is not { } mind || _removeRoleId == null)
            return;

        OnRemoveRole?.Invoke(mind, _removeRoleId);
    }

    private string GetMindLabel(AdminAntagMenuMindData mind)
    {
        var name = GetMindName(mind);
        if (mind.Username.Length > 0)
            name = Loc.GetString(EntryText, ("name", name), ("username", mind.Username));

        if (mind.Roles.Count == 0)
            return name;

        var roles = string.Join(", ", mind.Roles.Select(GetAntagName));
        return Loc.GetString(EntryRolesText, ("name", name), ("roles", roles));
    }

    private static string GetMindName(AdminAntagMenuMindData mind)
    {
        return mind.Name.Length > 0 ? mind.Name : Loc.GetString(UnknownNameText);
    }

    private string GetAntagName(string antag)
    {
        return _prototypes.TryIndex<AntagPrototype>(antag, out var prototype)
            ? Loc.GetString(prototype.Name)
            : antag;
    }

    private string GetObjectiveName(string prototype)
    {
        return _prototypes.TryIndex<EntityPrototype>(prototype, out var entityPrototype)
            ? entityPrototype.Name
            : prototype;
    }
}
